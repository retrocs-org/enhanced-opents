# Converts the STRINGTABLE blocks of a Windows resource script into a C++ initializer list
# for the POSIX port, which has no resource DLL to call LoadString on.
#
# usage: rcstrings.py language.rc language.h output.inc
#
# Each output line is `{ id, "text" },` with the text kept as a C string literal. Resource
# script literals escape a quote by doubling it; that is rewritten to \". Backslash escapes
# mean the same in both languages and pass through.

import re
import sys


def read_ids(header_path):
    ids = {}
    pattern = re.compile(r'^\s*#define\s+(\w+)\s+(\d+)')
    with open(header_path, encoding='utf-8', errors='replace') as header:
        for line in header:
            match = pattern.match(line)
            if match:
                ids[match.group(1)] = int(match.group(2))
    return ids


def tokens(text):
    """Yields identifiers, numbers, BEGIN/END and string literals, skipping comments."""
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c.isspace() or c == ',':
            i += 1
        elif text.startswith('//', i):
            i = text.find('\n', i)
            if i < 0:
                return
        elif text.startswith('/*', i):
            i = text.find('*/', i) + 2
        elif c == '"':
            j = i + 1
            out = []
            while j < n:
                if text[j] == '"':
                    if j + 1 < n and text[j + 1] == '"':
                        out.append('\\"')
                        j += 2
                        continue
                    break
                if text[j] == '\\' and j + 1 < n:
                    out.append(text[j:j + 2])
                    j += 2
                    continue
                if text[j] == '\n':
                    out.append('\\n')
                elif text[j] == '\r':
                    pass
                else:
                    out.append(text[j])
                j += 1
            yield ('str', ''.join(out))
            i = j + 1
        else:
            j = i
            while j < n and not text[j].isspace() and text[j] not in ',"':
                j += 1
            yield ('word', text[i:j])
            i = j


def main():
    rc_path, header_path, out_path = sys.argv[1:4]
    ids = read_ids(header_path)
    with open(rc_path, encoding='utf-8', errors='replace') as rc:
        text = rc.read()

    entries = {}
    toks = list(tokens(text))
    i = 0
    while i < len(toks):
        kind, value = toks[i]
        if kind == 'word' and value == 'STRINGTABLE':
            while i < len(toks) and toks[i] != ('word', 'BEGIN'):
                i += 1
            i += 1
            pending = None
            while i < len(toks) and toks[i] != ('word', 'END'):
                kind, value = toks[i]
                if kind == 'word':
                    pending = value
                elif pending is not None:
                    key = ids.get(pending)
                    if key is None and pending.isdigit():
                        key = int(pending)
                    if key is None:
                        sys.exit(f'rcstrings.py: unknown string identifier {pending}')
                    entries[key] = value
                    pending = None
                i += 1
        i += 1

    if not entries:
        sys.exit('rcstrings.py: no STRINGTABLE entries found')

    lines = ['/* Generated by tools/rcstrings.py from language.rc. Edits are overwritten. */\n']
    for key in sorted(entries):
        lines.append(f'{{ {key}, "{entries[key]}" }},\n')
    content = ''.join(lines)

    try:
        with open(out_path, encoding='utf-8') as existing:
            if existing.read() == content:
                return
    except OSError:
        pass
    with open(out_path, 'w', encoding='utf-8') as out:
        out.write(content)


if __name__ == '__main__':
    main()
